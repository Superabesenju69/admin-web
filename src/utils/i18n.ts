export function t(key: string, _lang?: string): string {
    const lang = _lang || 'es';
    // @ts-ignore
    return dictionary[lang]?.[key] || key;
}

export function formatRole(role?: string, lang: string = 'es'): string {
    if (!role) return '';
    const l = lang === 'en' ? 'en' : 'es';
    const roleMap: Record<string, { es: string; en: string }> = {
        system_admin: { es: 'Admin del Sistema', en: 'System Admin' },
        super_admin: { es: 'Super Administrador', en: 'Super Admin' },
        owner: { es: 'Propietario', en: 'Owner' },
        admin: { es: 'Administrador', en: 'Administrator' },
        cajero: { es: 'Cajero', en: 'Cashier' },
        mesero: { es: 'Mesero', en: 'Waiter' },
        cocinero: { es: 'Cocinero', en: 'Cook' },
        estacion: { es: 'Estación de Cocina', en: 'Kitchen Station' },
    };
    if (roleMap[role]) {
        return roleMap[role][l];
    }
    return role.replace('_', ' ');
}

